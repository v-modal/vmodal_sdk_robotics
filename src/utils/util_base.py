def os_makedirs(path: str) -> str:
    os.makedirs(path, exist_ok=True)
    return path


def os_path_cleanup(path: str):
    if os.path.isdir(path) and not os.path.islink(path):
        shutil.rmtree(path)
    elif os.path.lexists(path):
        os.unlink(path)
